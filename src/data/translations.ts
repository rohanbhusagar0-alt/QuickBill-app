/**
 * Returns localized string with graceful fallback, preserving all numbers
 */
export function getTranslation(lang: Language, key: string, fallback?: string): string {
  if (translations[lang] && translations[lang][key]) {
    return translations[lang][key];
  }
  if (moreTranslations[lang] && moreTranslations[lang][key]) {
    return moreTranslations[lang][key];
  }

  // English requested
  if (lang === 'en') {
    if (translations.en && translations.en[key]) return translations.en[key];
    if (moreTranslations.en && moreTranslations.en[key]) return moreTranslations.en[key];
    // Only use fallback if it is NOT Hindi/Devanagari
    if (fallback && !/[\u0900-\u097F]/.test(fallback)) return fallback;
    // Format key into readable English title
    return key
      .replace(/_/g, ' ')
      .replace(/\b\w/g, (c) => c.toUpperCase());
  }

  // Hindi requested
  if (lang === 'hi') {
    if (translations.hi && translations.hi[key]) return translations.hi[key];
    if (moreTranslations.hi && moreTranslations.hi[key]) return moreTranslations.hi[key];
    if (fallback && /[\u0900-\u097F]/.test(fallback)) return fallback;
  }

  // Generic fallback if provided
  if (fallback) {
    return fallback;
  }

  // Ultimate fallback
  if (translations.en && translations.en[key]) return translations.en[key];
  if (translations.hi && translations.hi[key]) return translations.hi[key];
  return key;
}
